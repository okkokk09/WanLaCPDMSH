export function getHolidayInfo(dateStr: string): HolidayInfo | null {
  if (!dateStr) return null;
  if (THAI_HOLIDAYS_BY_DATE[dateStr]) {
    return { date: dateStr, name: THAI_HOLIDAYS_BY_DATE[dateStr] };
  }
  const mmdd = dateStr.slice(5);
  if (RECURRING_FIXED_HOLIDAYS[mmdd]) {
    return { date: dateStr, name: RECURRING_FIXED_HOLIDAYS[mmdd] };
  }
  return null;
}

/**
 * ตรวจสอบว่าวันที่ระบุเป็นวันหยุดราชการ/นักขัตฤกษ์หรือไม่
 */
export function isThaiPublicHoliday(dateStr: string): boolean {
  return getHolidayInfo(dateStr) !== null;
}

/**
 * ค้นหารายการวันหยุดราชการทั้งหมดที่อยู่ในช่วงวันที่กำหนด (startDate ถึง endDate)
 */
export function getHolidaysInRange(startDateStr: string, endDateStr: string): PublicHoliday[] {
  if (!startDateStr || !endDateStr || startDateStr > endDateStr) return [];
  const list: PublicHoliday[] = [];
  const start = new Date(startDateStr + 'T00:00:00');
  const end = new Date(endDateStr + 'T00:00:00');
  const cur = new Date(start);

  while (cur <= end) {
    const y = cur.getFullYear();
    const m = String(cur.getMonth() + 1).padStart(2, '0');
    const d = String(cur.getDate()).padStart(2, '0');
    const dStr = `${y}-${m}-${d}`;
    const hol = getHolidayInfo(dStr);
    if (hol) {
      const yearBE = y + 543;
      list.push({
        date: dStr,
        name: hol.name,
        yearBE,
      });
    }
    cur.setDate(cur.getDate() + 1);
  }

  return list;
}
